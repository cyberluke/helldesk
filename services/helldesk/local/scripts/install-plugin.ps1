# CyberLuke Local HELLDESK — register the Kilo plugin via supported discovery.
# Kilo auto-discovers every `.ts` file in `~/.config/kilo/plugin/`. This script
# writes a shim `<user-plugin-dir>/local-helldesk.ts` that re-exports the real
# plugin factory from this repo. It NEVER touches `clean-system-prompt.ts`.
#
#   .\scripts\install-plugin.ps1            # register (idempotent)
#   .\scripts\install-plugin.ps1 -Uninstall # remove shim only
param([switch]$Uninstall)

$ErrorActionPreference = "Stop"

$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$root = Resolve-Path (Join-Path $here "..")          # services/helldesk/local
$pluginDir = Join-Path $env:USERPROFILE ".config\kilo\plugin"
$target = Join-Path $pluginDir "local-helldesk.ts"
$cleanFile = Join-Path $pluginDir "clean-system-prompt.ts"

New-Item -ItemType Directory -Force -Path $pluginDir | Out-Null

if ($Uninstall) {
    if (Test-Path $target) { Remove-Item -Force $target; Write-Host "[install] removed $target" }
    else { Write-Host "[install] shim not present (nothing to remove)" }
    if (Test-Path $cleanFile) { Write-Host "[install] preserved clean-system-prompt.ts" }
    exit 0
}

# Refuse to clobber any existing shim we did not create.
if (Test-Path -LiteralPath $target) {
    $existing = Get-Content -LiteralPath $target -Raw -ErrorAction SilentlyContinue
    if (-not $existing -or -not ($existing -match 'local-helldesk|REPO_PATH')) {
        throw "Refusing to overwrite existing $target (not created by this installer)."
    }
    Remove-Item -LiteralPath $target -Force
}

$repoPath = $root.Path   # full path to services/helldesk/local
$shim = @(
"// Auto-generated by install-plugin.ps1 — do not edit."
"import { LocalHelldeskPlugin } from '$($repoPath.Replace('\','/'))/plugin/index.ts';"
"export default {"
"  id: 'cyberluke-local-helldesk',"
"  server: LocalHelldeskPlugin,"
"};"
""
) -join "`n"

[System.IO.File]::WriteAllText($target, $shim, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "[install] wrote $target"

if (Test-Path $cleanFile) { Write-Host "[install] clean-system-prompt.ts untouched (co-exists; ids differ)" }
Write-Host "[install] Kilo will discover local-helldesk.ts on next VS Code start. Live-host verification is the operator's final step (no live Kilo host in the build sandbox)."